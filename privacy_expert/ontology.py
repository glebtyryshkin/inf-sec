"""Онтология предметной области «конфиденциальность и тайны по законодательству РФ».

Модуль содержит словари маркеров (лингвистических признаков) для извлечения
сущностей четырёх типов:

* субъекты  — тот, кто действует, и тот, кто получает сведения;
* объекты   — охраняемые законом виды информации;
* действия  — что именно сделали со сведениями;
* контекст  — обстоятельства: согласие, правовое основание, вид документа и т.п.

Маркеры заданы «стемами» (основами слов) с квантификатором ``\\w*``, поэтому
система распознаёт словоформы («передал», «передали», «передача», «передаче»),
а не только точные вхождения ключевых слов.
"""
from __future__ import annotations

import re
from typing import Dict, List

# ---------------------------------------------------------------------------
# Вспомогательные функции
# ---------------------------------------------------------------------------


def cue(*patterns: str) -> re.Pattern:
    """Скомпилировать набор шаблонов в один регистронезависимый шаблон."""
    return re.compile("|".join("(?:%s)" % p for p in patterns), re.IGNORECASE)



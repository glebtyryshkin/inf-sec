# -*- coding: utf-8 -*-
"""База правил экспертной системы (продукционная модель).

Правило = набор условий + правовой вывод.  Условия проверяются на рабочей
памяти; правило может:

* **сработать** (все условия выполнены) — тогда формируется правовой вывод
  с указанием федерального закона, статьи, обоснования и рекомендуемого
  действия;
* **не сработать** (хотя бы одно условие нарушено);
* **сработать частично** (все условия выполнены либо неизвестны) — тогда
  система сообщает «Требуется ручная проверка» и задаёт уточняющие вопросы.

База содержит 20 правил: 4 вывода-выведения (промежуточные факты), 10 правил
юридической квалификации нарушений и 6 правил «законных исключений»,
информационных и служебных.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

from .facts import WorkingMemory

MATCH = "match"
MISS = "miss"
UNKNOWN = "unknown"

EXPLANATION_LIMIT = 4


# ---------------------------------------------------------------------------
# Условия
# ---------------------------------------------------------------------------
class Condition:
    """Базовое условие правила."""

    slots: Tuple[str, ...] = ()
    question: str = ""

    def evaluate(self, wm: WorkingMemory) -> str:  # pragma: no cover - абстрактный
        raise NotImplementedError

    def describe(self) -> str:  # pragma: no cover - абстрактный
        raise NotImplementedError

    def evidence(self, wm: WorkingMemory) -> List[str]:
        return []

    def matched_keys(self, wm: WorkingMemory) -> List[Tuple[str, str]]:
        return []


@dataclass
class Has(Condition):
    """В рабочей памяти должен быть факт предикат=значение."""

    predicate: str
    value: str
    label: str = ""

    def __post_init__(self) -> None:
        self.slots = (self.predicate,)

    def evaluate(self, wm: WorkingMemory) -> str:
        return MATCH if wm.holds(self.predicate, self.value) else MISS

    def describe(self) -> str:
        return self.label or "%s = %s" % (self.predicate, self.value)

    def evidence(self, wm: WorkingMemory) -> List[str]:
        fact = wm.get(self.predicate, self.value)
        return [fact.evidence] if fact and fact.evidence else []

    def matched_keys(self, wm: WorkingMemory) -> List[Tuple[str, str]]:
        return [(self.predicate, self.value)]


@dataclass
class AnyOf(Condition):
    """Должен присутствовать хотя бы один из перечисленных фактов."""

    predicate: str
    values: Sequence[str]
    label: str = ""

    def __post_init__(self) -> None:
        self.slots = (self.predicate,)

    def evaluate(self, wm: WorkingMemory) -> str:
        return MATCH if any(wm.holds(self.predicate, v) for v in self.values) else MISS

    def describe(self) -> str:
        return self.label or "%s ∈ {%s}" % (self.predicate, ", ".join(self.values))

    def evidence(self, wm: WorkingMemory) -> List[str]:
        out = []
        for value in self.values:
            fact = wm.get(self.predicate, value)
            if fact and fact.evidence:
                out.append(fact.evidence)
        return out

    def matched_keys(self, wm: WorkingMemory) -> List[Tuple[str, str]]:
        return [(self.predicate, v) for v in self.values if wm.holds(self.predicate, v)]


@dataclass
class Absent(Condition):
    """Факт предикат=значение не должен присутствовать (отрицание как неудача)."""

    predicate: str
    value: str
    label: str = ""

    def __post_init__(self) -> None:
        self.slots = (self.predicate,)

    def evaluate(self, wm: WorkingMemory) -> str:
        return MATCH if not wm.holds(self.predicate, self.value) else MISS

    def describe(self) -> str:
        return self.label or "не (%s = %s)" % (self.predicate, self.value)


@dataclass
class EmptySlot(Condition):
    """Слот вообще не заполнен (нет ни одного факта с таким предикатом)."""

    predicate: str
    label: str = ""

    def __post_init__(self) -> None:
        self.slots = (self.predicate,)

    def evaluate(self, wm: WorkingMemory) -> str:
        return MATCH if not wm.has_predicate(self.predicate) else MISS

    def describe(self) -> str:
        return self.label or "%s не определён" % self.predicate


@dataclass
class Ask(Condition):
    """Условие, которое при отсутствии данных даёт «неизвестно» и вопрос.

    Используется там, где закон требует установить конкретное обстоятельство
    (например, наличие согласия субъекта): если сведений нет, система не имеет
    права делать вывод и обязана запросить уточнение у пользователя.
    """

    predicate: str
    value: str
    question: str
    label: str = ""

    def __post_init__(self) -> None:
        self.slots = (self.predicate,)

    def evaluate(self, wm: WorkingMemory) -> str:
        if wm.holds(self.predicate, self.value):
            return MATCH
        if not wm.has_predicate(self.predicate):
            return UNKNOWN
        return MISS

    def describe(self) -> str:
        return self.label or "%s = %s" % (self.predicate, self.value)

    def evidence(self, wm: WorkingMemory) -> List[str]:
        fact = wm.get(self.predicate, self.value)
        return [fact.evidence] if fact and fact.evidence else []

    def matched_keys(self, wm: WorkingMemory) -> List[Tuple[str, str]]:
        return [(self.predicate, self.value)] if wm.holds(self.predicate, self.value) else []


# ---------------------------------------------------------------------------
# Правило
# ---------------------------------------------------------------------------
@dataclass
class Rule:
    """Продукционное правило «ЕСЛИ условие ТО вывод»."""

    rid: str
    title: str
    conditions: List[Condition]
    verdict: str                 # нарушение | законно | информация | ручная_проверка
    law: str = ""
    article: str = ""
    reason: str = ""
    action: str = "ничего не делать"      # удалить | маскировать | ничего не делать
    severity: str = "нет"                 # критический | высокий | средний | низкий | нет
    priority: int = 50
    conclusions: List[Tuple[str, str]] = field(default_factory=list)
    questions: Dict[str, str] = field(default_factory=dict)   # слот -> вопрос
    soft_questions: List[str] = field(default_factory=list)
    legal_note: str = ""
    #: Минимальная уверенность распознавания фактов, при которой правило даёт
    #: юридический вывод.  Если уверенность ниже (сведения распознаны по
    #: косвенным признакам), правило не срабатывает, а система запрашивает
    #: ручную проверку — это исключает ложные обвинения по догадке.
    min_confidence: float = 0.7
    #: Что нужно сделать для устранения нарушения (меры реагирования).
    remedy: str = ""

    def evaluate(self, wm: WorkingMemory):
        """Вернуть (статус, выполненные условия, неизвестные условия)."""
        matched: List[Condition] = []
        unknown: List[Condition] = []
        for cond in self.conditions:
            status = cond.evaluate(wm)
            if status == MISS:
                return MISS, [], []
            if status == UNKNOWN:
                unknown.append(cond)
            else:
                matched.append(cond)
        return (UNKNOWN if unknown else MATCH), matched, unknown

    def build_reason(self, wm: WorkingMemory, matched: List[Condition]) -> str:
        parts = []
        for cond in matched[:EXPLANATION_LIMIT]:
            ev = cond.evidence(wm)
            text = cond.describe()
            if ev:
                text += " (в тексте: «%s»)" % ev[0]
            parts.append(text)
        return self.reason + " Основания вывода: " + "; ".join(parts) + "."



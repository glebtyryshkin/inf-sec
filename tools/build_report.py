#: Порядок дочерних элементов w:pPr по схеме OOXML (важно для корректного
#: открытия документа Word/LibreOffice: элементы обязаны идти в этом порядке).
PPR_ORDER = [
    "pStyle", "keepNext", "keepLines", "pageBreakBefore", "framePr", "widowControl",
    "numPr", "suppressLineNumbers", "pBdr", "shd", "tabs", "suppressAutoHyphens",
    "kinsoku", "wordWrap", "overflowPunct", "topLinePunct", "autoSpaceDE",
    "autoSpaceDN", "bidi", "adjustRightInd", "snapToGrid", "spacing", "ind",
    "contextualSpacing", "mirrorIndents", "suppressOverlap", "jc", "textDirection",
    "textAlignment", "textboxTightWrap", "outlineLvl", "divId", "cnfStyle", "rPr",
    "sectPr", "pPrChange",
]
#: Порядок дочерних элементов w:tcPr
TCPR_ORDER = [
    "cnfStyle", "tcW", "gridSpan", "hMerge", "vMerge", "tcBorders", "shd", "noWrap",
    "tcMar", "textDirection", "tcFitText", "vAlign", "hideMark", "headers", "cellIns",
    "cellDel", "cellMerge", "tcPrChange",
]


def insert_ordered(parent, element, order) -> None:
    """Вставить элемент в parent с соблюдением порядка OOXML."""
    tag = element.tag.split("}")[1]
    position = order.index(tag) if tag in order else len(order)
    for index, child in enumerate(parent):
        child_tag = child.tag.split("}")[1]
        child_position = order.index(child_tag) if child_tag in order else len(order)
        if child_position > position:
            parent.insert(index, element)
            return
    parent.append(element)


BODY_SIZE = Pt(14)
TABLE_SIZE = Pt(12)
CODE_SIZE = Pt(10.5)
FONT = "Times New Roman"
CODE_FONT = "Courier New"


# ---------------------------------------------------------------------------
# Низкоуровневые помощники
# ---------------------------------------------------------------------------
class Builder:
    """Вставка элементов в произвольное место документа."""

    def __init__(self, document: Document) -> None:
        self.doc = document
        self.anchor = None  # lxml-элемент, после которого вставляем

    def set_anchor(self, paragraph) -> None:
        self.anchor = paragraph._p

    def _attach(self, element) -> None:
        if self.anchor is None:
            self.doc.element.body.append(element)
            self.anchor = element
        else:
            self.anchor.addnext(element)
            self.anchor = element

    # -- абзацы ---------------------------------------------------------
    def paragraph(self, text: str = "", style: Optional[str] = None, size=BODY_SIZE,
                  bold: bool = False, italic: bool = False, align: str = "both",
                  first_line: Optional[float] = 1.25, font: str = FONT,
                  space_before: int = 0, space_after: int = 0, line: float = 1.5,
                  left_indent: Optional[float] = None, hanging: Optional[float] = None,
                  color: Optional[Tuple[int, int, int]] = None, keep_with_next: bool = False,
                  num_id: Optional[int] = None):
        par = self.doc.add_paragraph(style=style)
        if text:
            run = par.add_run(text)
            run.font.name = font
            run.font.size = size
            run.bold = bold
            run.italic = italic
            if color:
                run.font.color.rgb = RGBColor(*color)
            rpr = run._element.get_or_add_rPr()
            rpr.rFonts.set(qn("w:eastAsia"), font)
            rpr.rFonts.set(qn("w:cs"), font)
        pf = par.paragraph_format
        pf.alignment = {
            "both": WD_ALIGN_PARAGRAPH.JUSTIFY,
            "center": WD_ALIGN_PARAGRAPH.CENTER,
            "left": WD_ALIGN_PARAGRAPH.LEFT,
        }.get(align, WD_ALIGN_PARAGRAPH.JUSTIFY)
        pf.line_spacing = line
        pf.space_before = Pt(space_before)
        pf.space_after = Pt(space_after)
        if first_line is not None and num_id is None:
            pf.first_line_indent = Cm(first_line)
        if left_indent is not None:
            pf.left_indent = Cm(left_indent)
        if hanging is not None:
            pf.first_line_indent = Cm(-hanging)
        pf.keep_with_next = keep_with_next
        if num_id is not None:
            self._set_numbering(par, num_id)
        self._attach(par._p)
        return par

    @staticmethod
    def _set_numbering(par, num_id: int, level: int = 0) -> None:
        ppr = par._p.get_or_add_pPr()
        numpr = OxmlElement("w:numPr")
        ilvl = OxmlElement("w:ilvl")
        ilvl.set(qn("w:val"), str(level))
        numid = OxmlElement("w:numId")
        numid.set(qn("w:val"), str(num_id))
        numpr.append(ilvl)
        numpr.append(numid)
        insert_ordered(ppr, numpr, PPR_ORDER)

    def bullet(self, text: str, num_id: int = 1, size=BODY_SIZE):
        return self.paragraph(text, style="List Paragraph", size=size, num_id=num_id,
                              first_line=None, align="both")

    def code(self, lines: Sequence[str], size=CODE_SIZE):
        """Листинг/фрагмент консольного вывода моноширинным шрифтом."""
        for index, line in enumerate(lines):
            par = self.doc.add_paragraph()
            run = par.add_run(line if line else " ")
            run.font.name = CODE_FONT
            run.font.size = size
            rpr = run._element.get_or_add_rPr()
            rpr.rFonts.set(qn("w:eastAsia"), CODE_FONT)
            rpr.rFonts.set(qn("w:cs"), CODE_FONT)
            pf = par.paragraph_format
            pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
            pf.line_spacing = 1.0
            pf.space_before = Pt(0)
            pf.space_after = Pt(0)
            pf.left_indent = Cm(0.6)
            pf.first_line_indent = Cm(0)
            pf.keep_with_next = index < len(lines) - 1
            self._attach(par._p)

    # -- таблицы --------------------------------------------------------
    def table(self, header: Sequence[str], rows: Sequence[Sequence[str]],
              widths: Optional[Sequence[float]] = None, caption: str = "",
              font_size=TABLE_SIZE):
        if caption:
            self.paragraph(caption, size=Pt(12), align="left", first_line=None,
                           space_before=6, space_after=2, line=1.0, keep_with_next=True)
        table = self.doc.add_table(rows=1, cols=len(header))
        table.style = self.doc.styles["Table Grid"]
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = False
        for index, text in enumerate(header):
            cell = table.rows[0].cells[index]
            self._fill_cell(cell, text, bold=True, size=font_size, align="center")
            self._shade(cell, "DCE6F1")
        for row in rows:
            cells = table.add_row().cells
            for index, text in enumerate(row):
                align = "center" if index == 0 and len(str(text)) <= 3 else "left"
                self._fill_cell(cells[index], str(text), size=font_size, align=align)
        if widths:
            for row in table.rows:
                for index, width in enumerate(widths):
                    row.cells[index].width = Cm(width)
        self._attach(table._tbl)
        self.paragraph("", size=Pt(6), first_line=None, line=1.0, space_after=0)
        return table

    @staticmethod
    def _fill_cell(cell, text: str, bold: bool = False, size=TABLE_SIZE,
                   align: str = "left") -> None:
        cell.text = ""
        par = cell.paragraphs[0]
        run = par.add_run(text)
        run.font.name = FONT
        run.font.size = size
        run.bold = bold
        rpr = run._element.get_or_add_rPr()
        rpr.rFonts.set(qn("w:eastAsia"), FONT)
        par.paragraph_format.alignment = {
            "left": WD_ALIGN_PARAGRAPH.LEFT,
            "center": WD_ALIGN_PARAGRAPH.CENTER,
        }[align]
        par.paragraph_format.line_spacing = 1.0
        par.paragraph_format.space_before = Pt(1)
        par.paragraph_format.space_after = Pt(1)
        par.paragraph_format.first_line_indent = Cm(0)

    @staticmethod
    def _shade(cell, color: str) -> None:
        tc_pr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"), color)
        insert_ordered(tc_pr, shd, TCPR_ORDER)

    # -- рисунки --------------------------------------------------------
    def picture(self, path: str, caption: str, width_cm: float = CONTENT_WIDTH_CM,
                max_height_cm: float = MAX_IMAGE_HEIGHT_CM, size=Pt(12)):
        if not os.path.exists(path):
            raise FileNotFoundError(path)
        with Image.open(path) as image:
            px_w, px_h = image.size
        width = width_cm
        height = width_cm * px_h / px_w
        if height > max_height_cm:
            height = max_height_cm
            width = height * px_w / px_h
        par = self.doc.add_paragraph()
        par.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        par.paragraph_format.first_line_indent = Cm(0)
        par.paragraph_format.line_spacing = 1.0
        par.paragraph_format.space_before = Pt(6)
        par.paragraph_format.space_after = Pt(2)
        par.paragraph_format.keep_with_next = True
        par.add_run().add_picture(path, width=Cm(width), height=Cm(height))
        self._attach(par._p)
        self.paragraph(caption, size=size, align="center", first_line=None,
                       line=1.0, space_after=8)
        return par



def replace_placeholder(document: Document, needle: str, builder_factory) -> int:
    """Найти абзац-заготовку и заменить его содержимым."""
    for index, par in enumerate(document.paragraphs):
        if needle in par.text:
            par.text = ""
            return index
    return -1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Дописать раздел о Python-системе в отчёт ЛР2")
    parser.add_argument("--source", required=True, help="исходный docx")
    parser.add_argument("--output", required=True, help="итоговый docx")
    args = parser.parse_args(argv)

    document = Document(args.source)

    # 1) заготовка «Тут пиши» → позиция вставки
    placeholder = None
    for par in document.paragraphs:
        if par.text.strip().lower() in ("тут пиши", "тут пиши."):
            placeholder = par
            break
    if placeholder is None:
        print("Не найдена заготовка «Тут пиши»", file=sys.stderr)
        return 1

    builder = Builder(document)
    builder.set_anchor(placeholder)
    build_section(builder)

    # 2) убрать саму заготовку (её содержимое больше не нужно)
    placeholder._p.getparent().remove(placeholder._p)

    # 3) заключение
    for par in document.paragraphs:
        if par.text.strip().startswith("В ходе выполнения лабораторной работы №2 мы"):
            par.text = ""
            builder.set_anchor(par)
            for index, text in enumerate(CONCLUSION_TEXT):
                builder.paragraph(text, space_after=0)
            par._p.getparent().remove(par._p)
            break

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    document.save(args.output)
    print("Сохранено: %s" % args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
